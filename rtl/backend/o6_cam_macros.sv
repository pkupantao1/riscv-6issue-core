  // older[i][j] = 1：j 比 i 老
  logic [31:0] older [32];
  logic [7:0]  pd    [32];
  always_ff @(posedge clk_i) begin
    logic [31:0] nw;
    int          pt [32];
    for (int j = 0; j < 32; j++) begin
      nw[j] = 1'b0; pt[j] = 0;
      for (int k = 0; k < 4; k++) if (we_i[k][j]) begin nw[j] = 1'b1; pt[j] = k; end
    end
    for (int i = 0; i < 32; i++)
      if (nw[i]) begin
        // 新写的行：现存项都比它老；同拍新写的项里口号小的更老
        pd[i] <= pi_i[pt[i]];
        for (int j = 0; j < 32; j++) older[i][j] <= (j != i) && !(nw[j] && pt[j] >= pt[i]);
      end else
        for (int j = 0; j < 32; j++) if (nw[j]) older[i][j] <= 1'b0;    // 新项比所有现存项年轻
  end
  // R0 / R1 / EX 在宏内上升沿锁存 (2026-10-26 方案 2)：本拍求值用上一拍送进来的值 (调用方送下一拍的请求)
  logic [31:0] rl0, rl1, rlx;
  always_ff @(posedge clk_i) begin rl0 <= r0_i; rl1 <= r1_i; rlx <= ex_i; end
  always_comb begin
    logic [31:0] r0p, rx;
    r0p = rl0 & ~rlx;
    rx  = rl1 & rlx;
    g0_o = '0; g1_o = '0;
    for (int i = 0; i < 32; i++) begin
      // 口 0：r0p 中没有比 i 更老的
      if (r0p[i] && !(|(r0p & older[i]))) g0_o[i] = 1'b1;
      // 口 1：有只能走口 1 的就取其中最老，否则 r1 中最年轻 (没有比 i 更年轻的)
      if (|rx) begin
        if (rx[i] && !(|(rx & older[i]))) g1_o[i] = 1'b1;
      end else begin
        logic yng;
        yng = 1'b0;
        for (int j = 0; j < 32; j++) if (rl1[j] && older[j][i]) yng = 1'b1;      // j 比 i 年轻
        if (rl1[i] && !yng) g1_o[i] = 1'b1;
      end
    end
    c1_o = |(g0_o & g1_o);
    q0_o = '0; q1_o = '0;
    for (int i = 0; i < 32; i++) begin
      q0_o = q0_o | ({8{g0_o[i]}} & pd[i]);
      q1_o = q1_o | ({8{g1_o[i]}} & pd[i]);
    end
  end
`endif
endmodule

